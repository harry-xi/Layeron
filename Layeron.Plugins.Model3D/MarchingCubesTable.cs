    static MarchingCubesTable()
    {
        for (var e = 0; e < EdgeCorners.Length; e++)
        {
            var (a, b) = EdgeCorners[e];
            var oa = CornerOffsets[a];
            var ob = CornerOffsets[b];

            // The two corners of an edge differ in exactly one axis; that axis is the edge's direction.
            EdgeAxis[e] = oa.X != ob.X ? 0 : oa.Y != ob.Y ? 1 : 2;

            // The edge is identified by the lower of its two lattice points, which is the corner whose
            // offset carries the zero in the varying axis.
            EdgeOrigin[e] = new Vector3(
                MathF.Min(oa.X, ob.X),
                MathF.Min(oa.Y, ob.Y),
                MathF.Min(oa.Z, ob.Z));
        }
    }

    /// <summary>
    /// The triangle row for a configuration, as a span into the backing table.
    /// <para>
    /// Returning a span rather than a copy matters: this is the innermost call of the whole extractor,
    /// and copying sixteen integers per cell would allocate or copy far more than the geometry it
    /// produces.
    /// </para>
    /// </summary>
    public static ReadOnlySpan<int> Row(int configIndex)
        => MemoryMarshal.CreateReadOnlySpan(ref TriTable[configIndex, 0], RowLength);

    /// <summary>Number of triangles the table emits for a configuration (0 for the two empty cases).</summary>
    public static int TriangleCount(int configIndex)
    {
        var count = 0;

        for (var i = 0; i < RowLength; i += 3)
        {
            if (TriTable[configIndex, i] == Terminator)
                return count;

            count++;
        }

        return count;
    }

    /// <summary>
    /// Writes the edges whose endpoints have opposite membership into <paramref name="destination"/>
    /// and returns how many were written.
    /// <para>
    /// This is the property every row of the table must satisfy - an edge may appear in a row only
    /// if the level separates its two corners - and it is what the table validation test asserts for
    /// all 256 rows. The caller supplies the buffer because a stack-allocated span cannot be returned
    /// from a method, and allocating per row would defeat the point of the check being cheap.
    /// </para>
    /// </summary>
    public static int WriteCrossingEdges(int configIndex, Span<byte> destination)
    {
        var count = 0;

        for (var e = 0; e < 12; e++)
        {
            var (a, b) = EdgeCorners[e];
            var inA = (configIndex & (1 << a)) != 0;
            var inB = (configIndex & (1 << b)) != 0;

            if (inA != inB && count < destination.Length)
                destination[count++] = (byte)e;
        }

        return count;
    }
